"""Independent, hard-coded Decimal reference values (see VALIDATION.md).

The test expectations are NOT generated by the application engine.
"""

import math
import unittest

from engine import DesignInput, InputError, UnknownSection, calculate_tension, find_angle, load_catalog


class SectionCatalogTests(unittest.TestCase):
    def test_known_section_and_alias(self):
        self.assertEqual(find_angle("75 × 75 × 6").area_mm2, 875.0)
        self.assertEqual(find_angle("L75x75x6").name, "ISA 75x75x6")

    def test_unknown_section_exact_message(self):
        with self.assertRaisesRegex(UnknownSection, "please select correct section"):
            find_angle("ISA 79x79x7")

    def test_catalog_has_no_overlaps_and_positive_areas(self):
        self.assertGreaterEqual(len(load_catalog()), 8)
        self.assertTrue(all(a.area_mm2 > 0 for a in load_catalog().values()))


class IndependentReferenceCases(unittest.TestCase):
    """Hand-established reference values with Decimal arithmetic, kN."""

    def case(self, section, force, n, p, e, g, d):
        return calculate_tension(
            find_angle(section),
            DesignInput(force, 250.0, 410.0, n, d, p, e, g),
        )

    def assert_values(self, r, tdg, tdn, c1, c2):
        self.assertTrue(math.isclose(r.gross_yield_kn, tdg, abs_tol=0.000005))
        self.assertTrue(math.isclose(r.net_rupture_kn, tdn, abs_tol=0.000005))
        self.assertTrue(math.isclose(r.block_case_1_kn, c1, abs_tol=0.000005))
        self.assertTrue(math.isclose(r.block_case_2_kn, c2, abs_tol=0.000005))
        self.assertTrue(math.isclose(r.block_shear_kn, min(c1, c2), abs_tol=0.000005))

    def test_A_yielding_governs_and_passes(self):
        r = self.case("75x75x6", 160.0, n=4, p=100, e=70, g=35, d=18)
        self.assert_values(r, 198.86363636, 213.38315920, 346.20665400, 368.48451316)
        self.assertEqual(r.governing_mode, "Gross-section yielding")
        self.assertTrue(r.overall_pass)

    def test_B_rupture_governs_and_fails(self):
        r = self.case("50x50x5", 105.0, n=3, p=60, e=40, g=35, d=18)
        self.assert_values(r, 109.77272727, 102.43427642, 113.82877622, 115.04488924)
        self.assertEqual(r.governing_mode, "Net-section rupture")
        self.assertTrue(r.check(r.gross_yield_kn))
        self.assertFalse(r.check(r.net_rupture_kn))
        self.assertTrue(r.check(r.block_shear_kn))
        self.assertFalse(r.overall_pass)

    def test_C_block_shear_governs_and_fails(self):
        r = self.case("75x75x6", 180.0, n=3, p=60, e=40, g=35, d=18)
        self.assert_values(r, 198.86363636, 183.80887982, 180.87453146, 172.14477618)
        self.assertEqual(r.governing_mode, "Block shear")
        self.assertTrue(r.check(r.gross_yield_kn))
        self.assertTrue(r.check(r.net_rupture_kn))
        self.assertFalse(r.check(r.block_shear_kn))
        self.assertFalse(r.overall_pass)

    def test_amendment_beta_cap_applied(self):
        r = self.case("75x75x6", 50, n=4, p=300, e=50, g=35, d=18)
        self.assertAlmostEqual(r.beta_used, 0.9 * 410 * 1.10 / (250 * 1.25), places=9)
        self.assertGreater(r.beta_raw, r.beta_used)

    def test_default_demo_passes(self):
        r = self.case("ISA 75x75x6", 120.0, n=3, p=60, e=40, g=35, d=18)
        self.assertTrue(r.overall_pass)
        self.assertAlmostEqual(r.utilization, 120.0 / 172.14477618, places=8)

    def test_zero_load_rejected(self):
        with self.assertRaises(InputError):
            self.case("75x75x6", 0, n=3, p=60, e=40, g=35, d=18)

    def test_bad_hole_gauge_rejected(self):
        with self.assertRaisesRegex(InputError, "fit entirely"):
            self.case("50x50x5", 30, n=3, p=60, e=40, g=48, d=18)

    def test_invalid_material_rejected(self):
        with self.assertRaisesRegex(InputError, "exceed yield"):
            calculate_tension(find_angle("75x75x6"),
                              DesignInput(100, 410, 250, 3, 18, 60, 40, 35))

    def test_invalid_connection_one_bolt_rejected(self):
        with self.assertRaisesRegex(InputError, "At least two"):
            self.case("75x75x6", 30, n=1, p=60, e=40, g=35, d=18)


if __name__ == "__main__":
    unittest.main()
